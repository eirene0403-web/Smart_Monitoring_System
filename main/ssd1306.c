// ---------- Draw one character ----------
static void oled_write_char(char c) {
    if (c < 32 || c > 126) c = '?';
    for (int i = 0; i < 5; i++) oled_send_data(font5x7[c - 32][i]);
    oled_send_data(0x00);
}

// ---------- Draw string ----------
void oled_write_str(const char *str) {
    while (*str) oled_write_char(*str++);
}